// Email Configuration Wizard for ICSRT
const fs = require('fs');
const path = require('path');
const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

function question(prompt) {
  return new Promise((resolve) => {
    rl.question(prompt, resolve);
  });
}

async function setupEmailWizard() {
  console.log('🧙‍♂️ ICSRT Email Configuration Wizard');
  console.log('═══════════════════════════════════════');
  console.log('');
  console.log('This wizard will help you set up Gmail for email verification.');
  console.log('');
  console.log('📋 Prerequisites:');
  console.log('   1. Gmail account with 2-Factor Authentication enabled');
  console.log('   2. App Password generated for "Mail"');
  console.log('');
  console.log('🔑 To get Gmail App Password:');
  console.log('   1. Go to: https://myaccount.google.com/security');
  console.log('   2. Enable 2-Step Verification (if not already enabled)');
  console.log('   3. Click "App passwords"');
  console.log('   4. Generate password for "Mail"');
  console.log('   5. Copy the 16-character password');
  console.log('');
  
  const ready = await question('Are you ready to continue? (y/n): ');
  if (ready.toLowerCase() !== 'y') {
    console.log('👋 Setup cancelled. Run this script again when ready.');
    rl.close();
    return;
  }
  
  console.log('');
  const email = await question('📧 Enter your Gmail address: ');
  
  if (!email.includes('@gmail.com')) {
    console.log('⚠️  Please use a Gmail address ending with @gmail.com');
    rl.close();
    return;
  }
  
  console.log('');
  console.log('🔐 Enter your Gmail App Password (16 characters):');
  console.log('   This is NOT your regular Gmail password!');
  const password = await question('App Password: ');
  
  if (password.length !== 16) {
    console.log('⚠️  Gmail App Passwords are exactly 16 characters long.');
    console.log('    Please generate a new App Password and try again.');
    rl.close();
    return;
  }
  
  // Create .env content
  const envContent = `# ICSRT Email Configuration
# Generated by Email Setup Wizard

# Your Gmail address
EMAIL_USER=${email}

# Your Gmail App Password (16 characters)
EMAIL_PASS=${password}

# Email service provider
EMAIL_SERVICE=gmail

# Development/Production mode
NODE_ENV=development`;
  
  // Write to .env file
  const envPath = path.join(__dirname, '.env');
  fs.writeFileSync(envPath, envContent);
  
  console.log('');
  console.log('✅ Email configuration saved to .env file!');
  console.log('');
  console.log('🧪 Testing email configuration...');
  
  rl.close();
  
  // Test the email configuration
  try {
    require('dotenv').config();
    const nodemailer = require('nodemailer');
    
    const transporter = nodemailer.createTransport({
      service: 'gmail',
      auth: {
        user: email,
        pass: password
      },
      tls: {
        rejectUnauthorized: false
      }
    });
    
    await transporter.verify();
    console.log('✅ Email configuration test successful!');
    console.log('');
    console.log('🎉 Setup Complete!');
    console.log('📝 Next steps:');
    console.log('   1. Restart your ICSRT server: node server.js');
    console.log('   2. Try signing up with a real email address');
    console.log('   3. Check your inbox for verification emails');
    console.log('');
    console.log('🚀 Email verification is now fully functional!');
    
  } catch (error) {
    console.log('❌ Email test failed:', error.message);
    console.log('');
    console.log('🔧 Troubleshooting:');
    console.log('   1. Double-check your Gmail App Password');
    console.log('   2. Make sure 2-Factor Authentication is enabled');
    console.log('   3. Try generating a new App Password');
    console.log('   4. Check your internet connection');
  }
}

setupEmailWizard().catch(console.error);
