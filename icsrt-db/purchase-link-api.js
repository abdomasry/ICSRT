const { ObjectId } = require('mongodb');
const crypto = require('crypto');

/**
 * Purchase Link Management API
 * Allows super admins to create purchase links for confirmed service orders
 */
function addPurchaseLinkAPI(app, connectDB) {
  
  // Generate a purchase link for a service order
  app.post('/api/admin/service-orders/:orderId/generate-purchase-link', async (req, res) => {
    try {
      const db = await connectDB();
      const { orderId } = req.params;
      const { adminEmail, expiryHours = 72 } = req.body;

      if (!orderId || !ObjectId.isValid(orderId)) {
        return res.status(400).json({
          success: false,
          error: 'Valid order ID is required'
        });
      }

      // Find the service order
      const order = await db.collection('service-orders').findOne({
        _id: new ObjectId(orderId)
      });

      if (!order) {
        return res.status(404).json({
          success: false,
          error: 'Service order not found'
        });
      }

      // Check if order is eligible for purchase link
      if (order.status !== 'confirmed' && order.status !== 'ready-for-payment') {
        return res.status(400).json({
          success: false,
          error: 'Order must be confirmed or ready for payment to generate purchase link'
        });
      }

      if (order.paymentStatus === 'paid' || order.paymentStatus === 'completed') {
        return res.status(400).json({
          success: false,
          error: 'Order has already been paid'
        });
      }

      // Generate unique purchase token
      const purchaseToken = crypto.randomBytes(32).toString('hex');
      const expiresAt = new Date(Date.now() + (expiryHours * 60 * 60 * 1000));

      // Create purchase link data
      const purchaseLinkData = {
        token: purchaseToken,
        orderId: new ObjectId(orderId),
        userEmail: order.userEmail,
        amount: order.totalAmount,
        currency: 'USD',
        createdBy: adminEmail,
        createdAt: new Date(),
        expiresAt: expiresAt,
        isActive: true,
        usageCount: 0,
        maxUsage: 1,
        metadata: {
          serviceName: order.serviceName,
          customerName: order.customerInfo?.name,
          customerEmail: order.customerInfo?.email
        }
      };

      // Save purchase link
  await db.collection('purchaseLinks').insertOne(purchaseLinkData);

      // Update service order with purchase link info
  await db.collection('service-orders').updateOne(
        { _id: new ObjectId(orderId) },
        {
          $set: {
            purchaseLink: {
              token: purchaseToken,
              createdAt: new Date(),
              expiresAt: expiresAt,
              createdBy: adminEmail,
              isActive: true
            },
            status: 'ready-for-payment',
            updatedAt: new Date()
          },
          $push: {
            statusHistory: {
              oldStatus: order.status,
              newStatus: 'ready-for-payment',
              reason: 'Purchase link generated by admin',
              changedBy: adminEmail,
              timestamp: new Date()
            }
          }
        }
      );

      // Generate the actual purchase URL
      const purchaseUrl = `http://localhost:3002/purchase/${purchaseToken}`;

      res.json({
        success: true,
        message: 'Purchase link generated successfully',
        purchaseLink: {
          token: purchaseToken,
          url: purchaseUrl,
          expiresAt: expiresAt,
          amount: order.totalAmount,
          currency: 'USD'
        }
      });

    } catch (error) {
      console.error('Error generating purchase link:', error);
      res.status(500).json({
        success: false,
        error: 'Failed to generate purchase link'
      });
    }
  });

  // Get purchase link details
  app.get('/api/purchase-link/:token', async (req, res) => {
    try {
      const db = await connectDB();
      const { token } = req.params;

      if (!token) {
        return res.status(400).json({
          success: false,
          error: 'Purchase token is required'
        });
      }

      // Find the purchase link
  const purchaseLink = await db.collection('purchaseLinks').findOne({ token });

      if (!purchaseLink) {
        return res.status(404).json({
          success: false,
          error: 'Invalid purchase link'
        });
      }

      // Check if link has expired
      if (new Date() > purchaseLink.expiresAt) {
        return res.status(410).json({
          success: false,
          error: 'Purchase link has expired'
        });
      }

      // Check if link is still active
      if (!purchaseLink.isActive) {
        return res.status(410).json({
          success: false,
          error: 'Purchase link is no longer active'
        });
      }

      // Check usage limit
      if (purchaseLink.usageCount >= purchaseLink.maxUsage) {
        return res.status(410).json({
          success: false,
          error: 'Purchase link has reached maximum usage'
        });
      }

      // Get the associated service order
      const order = await db.collection('service-orders').findOne({
        _id: purchaseLink.orderId
      });

      if (!order) {
        return res.status(404).json({
          success: false,
          error: 'Associated service order not found'
        });
      }

      // Check if order is still eligible for payment
      if (order.paymentStatus === 'paid' || order.paymentStatus === 'completed') {
        return res.status(400).json({
          success: false,
          error: 'Order has already been paid'
        });
      }

      res.json({
        success: true,
        purchaseLink: {
          token: purchaseLink.token,
          amount: purchaseLink.amount,
          currency: purchaseLink.currency,
          expiresAt: purchaseLink.expiresAt,
          metadata: purchaseLink.metadata
        },
        order: {
          _id: order._id,
          serviceName: order.serviceName,
          description: order.description,
          totalAmount: order.totalAmount,
          customerInfo: order.customerInfo,
          status: order.status,
          paymentStatus: order.paymentStatus
        }
      });

    } catch (error) {
      console.error('Error fetching purchase link:', error);
      res.status(500).json({
        success: false,
        error: 'Failed to fetch purchase link details'
      });
    }
  });

  // Deactivate a purchase link
  app.post('/api/admin/purchase-links/:token/deactivate', async (req, res) => {
    try {
      const db = await connectDB();
      const { token } = req.params;
      const { adminEmail, reason } = req.body;

      const result = await db.collection('purchaseLinks').updateOne(
        { token },
        {
          $set: {
            isActive: false,
            deactivatedAt: new Date(),
            deactivatedBy: adminEmail,
            deactivationReason: reason || 'Deactivated by admin'
          }
        }
      );

      if (result.matchedCount === 0) {
        return res.status(404).json({
          success: false,
          error: 'Purchase link not found'
        });
      }

      res.json({
        success: true,
        message: 'Purchase link deactivated successfully'
      });

    } catch (error) {
      console.error('Error deactivating purchase link:', error);
      res.status(500).json({
        success: false,
        error: 'Failed to deactivate purchase link'
      });
    }
  });

  // List all purchase links for an order
  app.get('/api/admin/service-orders/:orderId/purchase-links', async (req, res) => {
    try {
      const db = await connectDB();
      const { orderId } = req.params;

      if (!orderId || !ObjectId.isValid(orderId)) {
        return res.status(400).json({
          success: false,
          error: 'Valid order ID is required'
        });
      }

  const purchaseLinks = await db.collection('purchaseLinks')
        .find({ orderId: new ObjectId(orderId) })
        .sort({ createdAt: -1 })
        .toArray();

      res.json({
        success: true,
        purchaseLinks
      });

    } catch (error) {
      console.error('Error fetching purchase links:', error);
      res.status(500).json({
        success: false,
        error: 'Failed to fetch purchase links'
      });
    }
  });

  console.log('✅ Purchase Link API endpoints loaded');
}

module.exports = { addPurchaseLinkAPI };
